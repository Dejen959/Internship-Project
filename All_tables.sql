------------------------------------------
---------FINANCIAL INSTITUTION------------
------------------------------------------
CREATE TABLE financial_institution (
    institution_id    NUMBER(10) NOT NULL,
    institution_code  VARCHAR2(20) NOT NULL,
    institution_name  VARCHAR2(100) NOT NULL,
    institution_type  VARCHAR2(30) NOT NULL,
    status            VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_financial_institution
        PRIMARY KEY (institution_id),

    CONSTRAINT uq_fi_code
        UNIQUE (institution_code),

    CONSTRAINT ck_fi_type
        CHECK (institution_type IN (
            'BANK',
            'MOBILE_MONEY',
            'PAYMENT_OPERATOR',
            'FINTECH')),

    CONSTRAINT ck_fi_status
        CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

------------------------------------------
----------PAYMENT CHANNEL-----------------
------------------------------------------
CREATE TABLE payment_channel (
    channel_id    NUMBER(10) NOT NULL,
    channel_name  VARCHAR2(50) NOT NULL,
    description   VARCHAR2(200),
    status        VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_payment_channel
        PRIMARY KEY (channel_id),

    CONSTRAINT uq_pc_name
        UNIQUE (channel_name),

    CONSTRAINT ck_pc_status
        CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

--------------------------------
-------FAILUE REASON------------
--------------------------------
CREATE TABLE failure_reason (
    failure_reason_id  NUMBER(10) NOT NULL,
    reason_code        VARCHAR2(30) NOT NULL,
    reason_name        VARCHAR2(100) NOT NULL,
    description        VARCHAR2(300),
    status             VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_failure_reason
        PRIMARY KEY (failure_reason_id),

    CONSTRAINT uq_fr_code
        UNIQUE (reason_code),

    CONSTRAINT ck_fr_status
        CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
--------------------------------------
--------PAYMENT TRANSACTION-----------
--------------------------------------
CREATE TABLE payment_transaction (
    transaction_id             VARCHAR2(50) NOT NULL,
    transaction_date           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    source_institution_id      NUMBER(10) NOT NULL,
    destination_institution_id NUMBER(10) NOT NULL,
    channel_id                 NUMBER(10) NOT NULL,
    amount                     NUMBER(18,2) NOT NULL,
    currency                   VARCHAR2(10) DEFAULT 'ETB' NOT NULL,
    transaction_status         VARCHAR2(20) NOT NULL,
    response_code              VARCHAR2(20),
    created_at                 TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_payment_transaction
        PRIMARY KEY (transaction_id),

    CONSTRAINT fk_pt_source_institution
        FOREIGN KEY (source_institution_id)
        REFERENCES financial_institution(institution_id),

    CONSTRAINT fk_pt_destination_institution
        FOREIGN KEY (destination_institution_id)
        REFERENCES financial_institution(institution_id),

    CONSTRAINT fk_pt_channel
        FOREIGN KEY (channel_id)
        REFERENCES payment_channel(channel_id),

    CONSTRAINT ck_pt_amount
        CHECK (amount > 0),

    CONSTRAINT ck_pt_currency
        CHECK (currency IN ('ETB')),

    CONSTRAINT ck_pt_status
        CHECK (
            transaction_status IN
            ('SUCCESS', 'FAILED', 'PENDING')
        )
);

----------------------------------------
--------FAILED TRANSACTION--------------
----------------------------------------
CREATE TABLE failed_transaction (
    failed_transaction_id    NUMBER(15) GENERATED BY DEFAULT AS IDENTITY,
    transaction_id           VARCHAR2(50) NOT NULL,
    failure_reason_id        NUMBER(10) NOT NULL,
    failure_date             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    resolution_status        VARCHAR2(20)
                             DEFAULT 'OPEN' NOT NULL,
    resolution_date          TIMESTAMP,
    remarks                   VARCHAR2(500),
    created_at                TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_failed_transaction
        PRIMARY KEY (failed_transaction_id),

    CONSTRAINT uq_failed_transaction
        UNIQUE (transaction_id),

    CONSTRAINT fk_ft_transaction
        FOREIGN KEY (transaction_id)
        REFERENCES payment_transaction(transaction_id),

    CONSTRAINT fk_ft_failure_reason
        FOREIGN KEY (failure_reason_id)
        REFERENCES failure_reason(failure_reason_id),

    CONSTRAINT ck_ft_resolution_status
        CHECK (resolution_status IN
            ('OPEN', 'INVESTIGATING', 'RESOLVED'))
);

